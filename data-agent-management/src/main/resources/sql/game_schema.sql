-- =====================================================================
-- 游戏销量分析库（用于 Agent 分析历史游戏表现，预测下一款游戏销量）
-- 数据库：MySQL 8.x（兼容 5.7）
-- 说明：
--   1. game_types / game_platforms 为字典表
--   2. games 为分析主表，字段分为两类：
--      - 特征字段（影响因素）：开发/营销投入、团队、周期、是否IP、售价、评分、平台、类型等
--      - 目标字段（预测对象）：actual_sales（实际销量）、revenue（收入）
--   3. 数据均为编造的虚构游戏，但遵循真实行业规律：
--      - 手游单价低销量高，主机单价高销量较低
--      - IP 续作整体销量高于同类型原创
--      - 高评分普遍带来更高销量
--      - 投入对销量呈边际递减，营销投入影响比开发投入更显著
-- =====================================================================

-- 游戏类型表
CREATE TABLE IF NOT EXISTS game_types (
    id INT PRIMARY KEY AUTO_INCREMENT COMMENT '类型ID，主键自增',
    name VARCHAR(50) NOT NULL COMMENT '游戏类型名称'
) COMMENT='游戏类型表';

-- 游戏平台表
CREATE TABLE IF NOT EXISTS game_platforms (
    id INT PRIMARY KEY AUTO_INCREMENT COMMENT '平台ID，主键自增',
    name VARCHAR(50) NOT NULL COMMENT '平台名称'
) COMMENT='游戏平台表';

-- 游戏主表（Agent 销量分析 / 预测数据源）
CREATE TABLE IF NOT EXISTS games (
    id INT PRIMARY KEY AUTO_INCREMENT COMMENT '游戏ID，主键自增',
    name VARCHAR(100) NOT NULL COMMENT '游戏名称',
    type_id INT NOT NULL COMMENT '游戏类型ID（外键 game_types.id）',
    platform_id INT NOT NULL COMMENT '主要发行平台ID（外键 game_platforms.id）',
    dev_budget DECIMAL(12,2) NOT NULL COMMENT '开发资金投入（万元）',
    marketing_budget DECIMAL(12,2) NOT NULL COMMENT '营销资金投入（万元）',
    total_investment DECIMAL(12,2) NOT NULL COMMENT '总资金投入（万元）= 开发 + 营销',
    team_size INT NOT NULL COMMENT '开发团队规模（人）',
    dev_months INT NOT NULL COMMENT '开发周期（月）',
    is_ip TINYINT(1) NOT NULL DEFAULT 0 COMMENT '是否为知名IP/续作（0否 1是）',
    price DECIMAL(8,2) NOT NULL COMMENT '售价（元），手游多为低价买断',
    review_score DECIMAL(3,1) NOT NULL COMMENT '玩家综合评分（0-10）',
    release_year INT NOT NULL COMMENT '发行年份',
    actual_sales DECIMAL(12,2) NOT NULL COMMENT '实际销量（万份）【预测目标变量】',
    revenue DECIMAL(12,2) NOT NULL COMMENT '总收入（万元）= 售价 × 销量',
    created_at DATETIME DEFAULT CURRENT_TIMESTAMP COMMENT '入库时间',
    KEY idx_type (type_id),
    KEY idx_platform (platform_id),
    KEY idx_year (release_year),
    KEY idx_sales (actual_sales),
    CONSTRAINT fk_games_type FOREIGN KEY (type_id) REFERENCES game_types(id),
    CONSTRAINT fk_games_platform FOREIGN KEY (platform_id) REFERENCES game_platforms(id)
) COMMENT='游戏销量分析主表';

